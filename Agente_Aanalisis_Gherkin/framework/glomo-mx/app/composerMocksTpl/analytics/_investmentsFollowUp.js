module.exports = () => {
  const CONSTANTS = require('./common/_constants');
  const utils = require('./common/_utils');
  const LITERALS = require('./common/_literals');

  const ANALYTICS_COMMON_INVEST_FEATURE_FLAG = {
    key: 'glomo.analytics.invest',
    defaultValue: true
  };

  const ANALYTICS_INVEST_ACCESS_FEATURE_FLAG = {
    key: 'glomo.analytics.invest.access',
    defaultValue: true
  };

  const ANALYTICS_INVEST_DASHBOARD_DATE_FLAG = {
    key: 'glomo.analytics.invest.dashboardDate',
    defaultValue: true
  };

  const COMMON_DATA = {
    [CONSTANTS.APPLICATION_FULLFILMENT]: LITERALS.empty,
    [CONSTANTS.PAGE_PAGEINFO_AREA]: LITERALS.commons.private,
    [CONSTANTS.PAGE_PAGEINFO_PAGEINTENT]: LITERALS.commons.information,
    [CONSTANTS.PAGE_PAGEINFO_PAGESEGMENT]: LITERALS.commons.persons,
    [CONSTANTS.PAGE_PAGEINFO_PROJECTNAME]: LITERALS.sections.glomo
  };

  const COMMON_DATA_INVEST = {
    ...COMMON_DATA,
    [CONSTANTS.PAGE_PAGEINFO_LEVEL1]: LITERALS.commons.investments
  };

  const COMMON_DATA_DASHBOARD_GLOMO = {
    ...COMMON_DATA,
    [CONSTANTS.PAGE_PAGEINFO_LEVEL1]: LITERALS.commons.investments,
    [CONSTANTS.PAGE_PAGEINFO_PROJECTNAME]: LITERALS.sections.glomo
  };

  const DYNAMIC_DATA = {
    [CONSTANTS.APPLICATION_INTERACTION_LEVEL]: {
      bind: 'dashboardDate'
    },
    [CONSTANTS.PAGE_PAGEINFO_LEVEL2]: {
      bind: 'dashboardTab'
    }
  };

  const DYNAMIC_LEVEL3 = {
    [CONSTANTS.PAGE_PAGEINFO_LEVEL3]: {
      bind: 'faqAnalyticsTitle'
    }
  };

  const footPrintLevel2 = (common) => (utils.getAdvancedFootprintWithLevel2(common, COMMON_DATA_INVEST));

  const INVESTMENTS_ACCESS_PAGE_VIEW = utils.getInternalLink(LITERALS.commons.checkEvolution, LITERALS.commons.global_position);

  const INVESTMENTS_DASHBOARD_VALUE_PAGE_VIEW = footPrintLevel2(LITERALS.commons.dashboardValue);

  const INVESTMENTS_DASHBOARD_PROFITABILITY_PAGE_VIEW = footPrintLevel2(LITERALS.commons.dashboardProfitability);

  const INVESTMENTS_MORE_INFORMATION_PRODUCTS_PAGE_VIEW = footPrintLevel2(LITERALS.commons.productMoreInfo);

  const INVESTMENTS_MORE_INFORMATION_FAMILIES_PAGE_VIEW = footPrintLevel2(LITERALS.commons.familyMoreInfo);

  const INVESTMENTS_SETTINGS_DATES_PAGE_VIEW = footPrintLevel2(LITERALS.commons.dateConfiguration);

  const INVESTMENTS_DASHBOARD_DATE_INTERACTION_LINK = utils.getInteractionLink('', {...COMMON_DATA_INVEST, ...DYNAMIC_DATA});

  const INVESTMENTS_FAQS_PAGE_VIEW = footPrintLevel2(LITERALS.commons.faqs);

  const INVESTMENTS_DESCRIPTION_GRAPH_PAGE_VIEW = utils.getAdvancedFootprintWithLevel2(LITERALS.commons.graphicDescription, {...COMMON_DATA_DASHBOARD_GLOMO});

  const INVESTMENTS_DETAIL_ARTICLE_PAGE_VIEW = utils.getAdvancedFootprintWithLevel3(LITERALS.commons.detail, {...COMMON_DATA_DASHBOARD_GLOMO, [CONSTANTS.PAGE_PAGEINFO_LEVEL2]: LITERALS.commons.learnToInvest});

  const INVESTMENTS_FAQS_QUESTIONS_PAGE_VIEW = {
    type: LITERALS.types.view,
    action: LITERALS.actions.mark,
    [CONSTANTS.DATALAYER_NAME]: {
      ...COMMON_DATA_INVEST,
      ...DYNAMIC_LEVEL3,
      [CONSTANTS.PAGE_PAGEINFO_LEVEL2]: LITERALS.commons.faqs
    }
  };

  const INVESTMENTS_SYSTEM_ERROR_PAGE_VIEW = {
    type: LITERALS.types.view,
    action: LITERALS.actions.mark,
    [CONSTANTS.DATALAYER_NAME]: {
      ...COMMON_DATA_INVEST,
      [CONSTANTS.PAGE_PAGEINFO_LEVEL2]: LITERALS.commons.systemError,
      [CONSTANTS.PAGE_PAGEINFO_ERRORPAGE]: LITERALS.commons.systemError
    }
  };
  const INVESTMENTS_TERMS_DESCRIPTION_PAGE_VIEW = footPrintLevel2(LITERALS.commons.termDescriptions);

  const INVESTMENTS_LEARN_TO_INVEST_PAGE_VIEW = footPrintLevel2(LITERALS.commons.learnToInvest);

  [
    INVESTMENTS_DASHBOARD_VALUE_PAGE_VIEW,
    INVESTMENTS_DASHBOARD_PROFITABILITY_PAGE_VIEW,
    INVESTMENTS_MORE_INFORMATION_PRODUCTS_PAGE_VIEW,
    INVESTMENTS_MORE_INFORMATION_FAMILIES_PAGE_VIEW,
    INVESTMENTS_SETTINGS_DATES_PAGE_VIEW,
    INVESTMENTS_FAQS_PAGE_VIEW,
    INVESTMENTS_DESCRIPTION_GRAPH_PAGE_VIEW,
    INVESTMENTS_DETAIL_ARTICLE_PAGE_VIEW,
    INVESTMENTS_FAQS_QUESTIONS_PAGE_VIEW,
    INVESTMENTS_TERMS_DESCRIPTION_PAGE_VIEW,
    INVESTMENTS_LEARN_TO_INVEST_PAGE_VIEW,
    INVESTMENTS_SYSTEM_ERROR_PAGE_VIEW
  ].forEach(item => utils.addFeatureFlag(item, ANALYTICS_COMMON_INVEST_FEATURE_FLAG));

  utils.addFeatureFlag(INVESTMENTS_ACCESS_PAGE_VIEW, ANALYTICS_INVEST_ACCESS_FEATURE_FLAG);
  utils.addFeatureFlag(INVESTMENTS_DASHBOARD_DATE_INTERACTION_LINK, ANALYTICS_INVEST_DASHBOARD_DATE_FLAG);

  return {
    INVESTMENTS_ACCESS_PAGE_VIEW,
    INVESTMENTS_DASHBOARD_VALUE_PAGE_VIEW,
    INVESTMENTS_DASHBOARD_PROFITABILITY_PAGE_VIEW,
    INVESTMENTS_MORE_INFORMATION_PRODUCTS_PAGE_VIEW,
    INVESTMENTS_MORE_INFORMATION_FAMILIES_PAGE_VIEW,
    INVESTMENTS_SETTINGS_DATES_PAGE_VIEW,
    INVESTMENTS_DASHBOARD_DATE_INTERACTION_LINK,
    INVESTMENTS_FAQS_PAGE_VIEW,
    INVESTMENTS_DESCRIPTION_GRAPH_PAGE_VIEW,
    INVESTMENTS_DETAIL_ARTICLE_PAGE_VIEW,
    INVESTMENTS_FAQS_QUESTIONS_PAGE_VIEW,
    INVESTMENTS_TERMS_DESCRIPTION_PAGE_VIEW,
    INVESTMENTS_LEARN_TO_INVEST_PAGE_VIEW,
    INVESTMENTS_SYSTEM_ERROR_PAGE_VIEW
  };
};
